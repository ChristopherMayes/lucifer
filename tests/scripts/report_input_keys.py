#!/usr/bin/env python3
"""
Generate docs/generated/input-keys.md from the schema the program writes.

  report_input_keys.py --schema python/lucifer/schema.json --out docs/generated/input-keys.md

One table per TOML table of the input file, in the input file's order, with each key's type, its
default as the program's structures declare it, its unit, its bounds or the set of names it
takes, and the one sentence the schema carries for it. A set that matches in any case is
written once, upper case, with "in any case" after it, since the schema's enum lists three
spellings of each name. docs/input-reference.md includes these tables
between its prose, so the key list, the defaults and the bounds come from the program
and the page says what the tables do not.
"""
import argparse
import json
from pathlib import Path

TYPE_NAMES = {"number": "real", "integer": "integer", "boolean": "true/false", "string": "string", "array": "list"}


def default_text(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return '`""`' if v == "" else f'`"{v}"`'
    if isinstance(v, list):
        return "`[" + ", ".join(str(default_text(x)).strip("`") for x in v) + "]`"
    if isinstance(v, float):
        return f"`{v:g}`"
    return f"`{v}`"


def bounds_text(p):
    parts = []
    if "exclusiveMinimum" in p:
        parts.append(f"above {p['exclusiveMinimum']:g}")
    elif "minimum" in p:
        parts.append(f"from {p['minimum']:g}")
    if "exclusiveMaximum" in p:
        parts.append(f"below {p['exclusiveMaximum']:g}")
    elif "maximum" in p:
        parts.append(f"up to {p['maximum']:g}")
    return ", ".join(parts)


def names_text(p):
    names = p["enum"]
    if p.get("x-any-case"):
        names = [n for n in names if n == n.upper()]
    text = ", ".join(f'`"{n}"`' for n in names)
    return text + " in any case" if p.get("x-any-case") else text


def table_rows(props):
    rows = []
    for name, p in props.items():
        if p.get("type") == "object":
            continue
        t = TYPE_NAMES.get(p["type"], p["type"])
        if p["type"] == "array":
            t = "list of " + TYPE_NAMES.get(p["items"]["type"], p["items"]["type"]) + "s"
        descrip = p.get("description", "")
        unit = ""
        if descrip.endswith("]") and " [" in descrip:
            descrip, unit = descrip.rsplit(" [", 1)
            unit = unit[:-1]
        limits = names_text(p) if "enum" in p else bounds_text(p)
        rows.append(f"| `{name}` | {t} | {default_text(p.get('default'))} | {unit} | {limits} | {descrip} |")
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--schema", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    schema = json.loads(Path(a.schema).read_text())
    props = schema["properties"]
    out = ["<!-- Generated by tests/scripts/report_input_keys.py from python/lucifer/schema.json,",
           "     which the program writes with `lucifer --schema`. Do not edit. -->", ""]
    header = "| key | type | default | unit | bounds or names | meaning |\n|---|---|---|---|---|---|"

    def block(label, name, rows):
        out.append(f"(keys-{label})=")
        out.append(f"### `{name}`" if name else "### The top level")
        out.append("")
        out.append(f"<!-- begin keys-{label} -->")
        out.append(header)
        out.extend(rows)
        out.append(f"<!-- end keys-{label} -->")
        out.append("")

    block("top", "", table_rows({k: v for k, v in props.items() if v.get("type") != "object"}))
    for tname, tprops in props.items():
        if tprops.get("type") != "object":
            continue
        block(tname, f"[{tname}]", table_rows(tprops["properties"]))
        for sub, sprops in tprops["properties"].items():
            if sprops.get("type") == "object":
                block(f"{tname}-{sub}", f"[{tname}.{sub}]", table_rows(sprops["properties"]))
    out.append(f"Schema version {schema.get('x-schema-version', '?')}.")
    Path(a.out).write_text("\n".join(out) + "\n")
    print(f"{a.out}: {sum(1 for l in out if l.startswith('| `'))} keys")


if __name__ == "__main__":
    main()
